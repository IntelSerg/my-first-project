# Вывод списка задач на экран
def показать_задачи(задачи):
    if not задачи:
        print("Список дел пуст.")
        return
    print("\n--- Список дел ---")
    for i, задача in enumerate(задачи, 1):
        статус = "[x]" if задача["выполнена"] else "[ ]"
        print(f"{i}. {статус} {задача['текст']}")
    print()


# Добавление новой задачи в список
def добавить_задачу(задачи, текст):
    задачи.append({"текст": текст, "выполнена": False})
    print(f'Добавлено: "{текст}"')


# Отметить задачу как выполненную по номеру
def выполнить_задачу(задачи, номер):
    if 1 <= номер <= len(задачи):
        задачи[номер - 1]["выполнена"] = True
        print(f'Выполнено: "{задачи[номер - 1]["текст"]}"')
    else:
        print("Неверный номер задачи.")


# Удаление задачи из списка по номеру
def удалить_задачу(задачи, номер):
    if 1 <= номер <= len(задачи):
        удалённая = задачи.pop(номер - 1)
        print(f'Удалено: "{удалённая["текст"]}"')
    else:
        print("Неверный номер задачи.")


def main():
    # Список задач хранится в памяти во время работы программы
    задачи = []

    # Доступные команды и их описание
    команды = {
        "список":   "показать список",
        "добавить": "добавить задачу",
        "готово":   "отметить выполненной",
        "удалить":  "удалить задачу",
        "выход":    "выйти",
    }

    print("=== Список дел ===")
    print("Команды:", ", ".join(f"{к} — {о}" for к, о in команды.items()))

    while True:
        команда = input("\n> ").strip().lower()

        if команда == "список":
            показать_задачи(задачи)

        elif команда == "добавить":
            текст = input("Новая задача: ").strip()
            if текст:
                добавить_задачу(задачи, текст)

        elif команда == "готово":
            показать_задачи(задачи)
            try:
                номер = int(input("Номер задачи: "))
                выполнить_задачу(задачи, номер)
            except ValueError:
                print("Введите число.")

        elif команда == "удалить":
            показать_задачи(задачи)
            try:
                номер = int(input("Номер задачи: "))
                удалить_задачу(задачи, номер)
            except ValueError:
                print("Введите число.")

        elif команда == "выход":
            print("До свидания!")
            break

        else:
            print("Неизвестная команда. Доступны:", ", ".join(команды))


if __name__ == "__main__":
    main()
